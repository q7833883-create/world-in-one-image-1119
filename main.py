def png_bytes():
    # Average every 2x2 RGB sample; the result is an exact 1024x1024 RGB image.
    raw = bytearray()
    stride = W * 3
    for y in range(0, H, 2):
        raw.append(0)  # PNG filter: None
        row = y * stride
        for x in range(0, W, 2):
            p = row + x * 3
            for c in range(3):
                raw.append((canvas[p+c] + canvas[p+3+c] +
                            canvas[p+stride+c] + canvas[p+stride+3+c] + 2) // 4)

    def chunk(kind, data):
        return (struct.pack('>I', len(data)) + kind + data +
                struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff))

    result = b'\x89PNG\r\n\x1a\n'
    result += chunk(b'IHDR', struct.pack('>IIBBBBB', 1024, 1024, 8, 2, 0, 0, 0))
    result += chunk(b'IDAT', zlib.compress(bytes(raw), 9))
    return result + chunk(b'IEND', b'')


