def wrap(s, scale, width):
    lines = []
    line = ''
    for word in s.split(' '):
        candidate = line + (' ' if line else '') + word
        if text_width(candidate, scale) <= width:
            line = candidate
        else:
            if line:
                lines.append(line)
            assert text_width(word, scale) <= width
            line = word
    if line:
        lines.append(line)
    assert ' '.join(lines) == s
    assert all(text_width(line, scale) <= width for line in lines)
    return lines


def fit_block(s, width, scales, max_lines):
    for scale in scales:
        lines = wrap(s, scale, width)
        if len(lines) <= max_lines:
            break
    else:
        raise ValueError('Text cannot fit: ' + s)
    return lines, scale


def block(s, x, y, width, scales, max_lines, colour, bold=False):
    lines, scale = fit_block(s, width, scales, max_lines)
    for line in lines:
        text(line, x, y, scale, colour, bold)
        y += 17 * scale
    return y, len(lines)


def panel(x, y, width, height, kicker, headline, body, lead=False):
    x, y, width, height = [v * 2 for v in (x, y, width, height)]
    rect(x, y, width, height, NAVY)
    rect(x + 6, y + 6, width - 12, height - 12, PAPER)
    rect(x, y, width, 68, NAVY)
    assert text_width(kicker, 2) < width - 48
    text(kicker, x + 28, y + 20, 2, WHITE)
    headline_layout, headline_scale = fit_block(
        headline, width - 56, (4, 3) if lead else (3, 2), 2)
    body_layout, body_scale = fit_block(
        body, width - 56, (3, 2) if lead else (2,), 6)
    gap = 16
    text_height = (len(headline_layout) * 17 * headline_scale + gap +
                   len(body_layout) * 17 * body_scale)
    header_bottom = y + 68
    interior_height = y + height - 6 - header_bottom
    assert text_height <= interior_height - 20, (kicker, text_height, interior_height)
    top = header_bottom + (interior_height - text_height) // 2
    assert top >= header_bottom
    bottom, headline_lines = block(headline, x + 28, top, width - 56,
                                   (headline_scale,), 2, INK, True)
    bottom, body_lines = block(body, x + 28, bottom + gap, width - 56,
                              (body_scale,), 6, INK)
    assert bottom <= y + height - 16, (kicker, bottom, y + height)
    WRAP_COUNTS.append((kicker, headline_lines, body_lines))


