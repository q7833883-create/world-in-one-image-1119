canvas = bytearray(WHITE) * (W * H)


def rect(x, y, width, height, colour):
    assert 0 <= x <= x + width <= W and 0 <= y <= y + height <= H
    row = bytes(colour) * width
    for yy in range(y, y + height):
        start = (yy * W + x) * 3
        canvas[start:start + len(row)] = row


def text_width(s, scale):
    return max(0, (len(s) * 11 - 1) * scale)


def text(s, x, y, scale, colour, bold=False):
    for ch in s:
        glyph = FONT[ch]
        for gy, row in enumerate(glyph):
            for gx, cell in enumerate(row):
                if cell == '#':
                    rect(x + gx * scale, y + gy * scale,
                         scale + (1 if bold else 0), scale, colour)
